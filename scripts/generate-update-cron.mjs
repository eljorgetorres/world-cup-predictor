#!/usr/bin/env node
/**
 * Generate per-match GitHub Actions cron schedules for update-scores.yml.
 *
 * For each upcoming fixture, schedules a one-time run at kickoff + 2h 15m UTC
 * (buffer for stoppage/extra time). Deduplicates triggers within the same minute;
 * groups into 15-minute windows when cron count exceeds MAX_CRONS.
 *
 * Usage:
 *   node scripts/generate-update-cron.mjs           # write workflow
 *   node scripts/generate-update-cron.mjs --dry-run # print schedule only
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const WORKFLOW_PATH = join(ROOT, '.github/workflows/update-scores.yml');
const DRY_RUN = process.argv.includes('--dry-run');

/** Minutes after kickoff before we expect a final score in the feed. */
const KICKOFF_BUFFER_MS = (2 * 60 + 15) * 60 * 1000;
/** Merge triggers in the same window when over MAX_CRONS. */
const GROUP_WINDOW_MS = 15 * 60 * 1000;
const MAX_CRONS = 50;

const { UPCOMING_MATCHES } = await import('../src/data/upcomingMatches.js');
const { PLAYED_MATCHES } = await import('../src/data/playedMatches.js');

function todayUtc() {
  const now = new Date();
  return now.toISOString().slice(0, 10);
}

/** Same-day played fixtures (reference only — already finished). */
function sameDayPlayed() {
  const day = todayUtc();
  return PLAYED_MATCHES.filter((m) => m.date.startsWith(day));
}

function matchLabel(m) {
  return `${m.home}-${m.away}`;
}

function toCron(date) {
  const min = date.getUTCMinutes();
  const hour = date.getUTCHours();
  const dom = date.getUTCDate();
  const month = date.getUTCMonth() + 1;
  return `${min} ${hour} ${dom} ${month} *`;
}

function formatUtc(date) {
  return date.toISOString().replace('.000Z', 'Z');
}

function formatEt(date) {
  return date.toLocaleString('en-US', {
    timeZone: 'America/New_York',
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    timeZoneName: 'short',
  });
}

/**
 * Build trigger times for future upcoming matches.
 * Returns [{ time: Date, matches: [{ home, away, kickoff }] }]
 */
function buildTriggers(now = Date.now()) {
  const byTrigger = new Map();

  for (const match of UPCOMING_MATCHES) {
    const kickoff = new Date(match.date);
    const triggerMs = kickoff.getTime() + KICKOFF_BUFFER_MS;
    if (triggerMs <= now) continue;

    const trigger = new Date(triggerMs);
    const minuteKey = toCron(trigger);

    if (!byTrigger.has(minuteKey)) {
      byTrigger.set(minuteKey, { time: trigger, matches: [] });
    }
    byTrigger.get(minuteKey).matches.push({
      label: matchLabel(match),
      kickoff: formatUtc(kickoff),
    });
  }

  let entries = [...byTrigger.values()].sort((a, b) => a.time - b.time);

  if (entries.length > MAX_CRONS) {
    const buckets = new Map();
    for (const entry of entries) {
      const bucketStart =
        Math.floor(entry.time.getTime() / GROUP_WINDOW_MS) * GROUP_WINDOW_MS;
      const existing = buckets.get(bucketStart);
      if (!existing || entry.time > existing.time) {
        const merged = existing ?? { time: entry.time, matches: [] };
        merged.time = new Date(Math.max(merged.time.getTime(), entry.time.getTime()));
        merged.matches.push(...entry.matches);
        buckets.set(bucketStart, merged);
      } else {
        existing.matches.push(...entry.matches);
        if (entry.time > existing.time) existing.time = entry.time;
      }
    }
    entries = [...buckets.values()].sort((a, b) => a.time - b.time);
  }

  return entries;
}

function buildWorkflowYaml(triggers) {
  const generated = new Date().toISOString();
  const scheduleLines = [];

  scheduleLines.push('    # AUTO-GENERATED by scripts/generate-update-cron.mjs — do not edit schedule by hand.');
  scheduleLines.push(`    # Generated: ${generated}`);
  scheduleLines.push('    # Regenerate after schedule changes: node scripts/generate-update-cron.mjs');
  scheduleLines.push(
    '    # Per-match: kickoff + 2h15m UTC. GitHub cron is best-effort (may drift ±few min).',
  );

  if (triggers.length === 0) {
    scheduleLines.push('    # (no future per-match triggers — tournament may be over or all fixtures played)');
  } else {
    for (const { time, matches } of triggers) {
      const labels = matches.map((m) => m.label).join(', ');
      const kickoffs = [...new Set(matches.map((m) => m.kickoff))].join(', ');
      scheduleLines.push(
        `    - cron: '${toCron(time)}'  # ${labels} (kickoff ${kickoffs}) → ~${formatEt(time)}`,
      );
    }
  }

  scheduleLines.push('    # Fallback: every 20 min during WC 2026 (Jun 11–30, Jul 1–19) if feed lags or cron missed');
  scheduleLines.push("    - cron: '*/20 * 11-30 6 *'");
  scheduleLines.push("    - cron: '*/20 * 1-19 7 *'");

  return `name: Update World Cup scores

on:
  schedule:
${scheduleLines.join('\n')}
  workflow_dispatch:

permissions:
  contents: write

jobs:
  update-scores:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Setup Node
        uses: actions/setup-node@v4
        with:
          node-version: '20'

      - name: Fetch feed and regenerate data
        run: node scripts/update-from-feed.mjs

      - name: Commit and push if changed
        run: |
          git config user.name "github-actions[bot]"
          git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
          git add src/data/playedMatches.js src/data/upcomingMatches.js src/data/groups.js
          if git diff --staged --quiet; then
            echo "No score changes — skipping commit"
          else
            git commit -m "chore: auto-update scores from openfootball feed"
            git push
          fi
`;
}

function main() {
  const playedToday = sameDayPlayed();
  const triggers = buildTriggers();

  console.log(`Upcoming fixtures: ${UPCOMING_MATCHES.length}`);
  console.log(`Same-day played (reference): ${playedToday.length}`);
  console.log(`Per-match cron triggers: ${triggers.length}`);
  console.log('');

  for (const { time, matches } of triggers) {
    const labels = matches.map((m) => m.label).join(', ');
    console.log(`  ${toCron(time)}  ${labels}`);
    console.log(`    trigger ${formatUtc(time)} (~${formatEt(time)})`);
  }

  const yaml = buildWorkflowYaml(triggers);

  if (DRY_RUN) {
    console.log('\n--- workflow (dry-run) ---\n');
    console.log(yaml);
    return;
  }

  writeFileSync(WORKFLOW_PATH, yaml, 'utf8');
  console.log(`\nWrote ${WORKFLOW_PATH}`);
}

main();
